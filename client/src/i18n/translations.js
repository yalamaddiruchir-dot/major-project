export const normalizeLang = (raw) => {
  if (!raw) return 'en';
  const v = String(raw).trim().toLowerCase();
  if (v === 'te' || v === 'telugu' || v === 'regional') return 'te';
  if (v === 'hi' || v === 'hindi') return 'hi';
  return 'en';
};

export const getLanguageDisplayName = (code) => {
  const norm = normalizeLang(code);
  const found = SUPPORTED_LANGUAGES.find((l) => l.code === norm);
  return found ? found.nativeLabel : String(code || 'EN').toUpperCase();
};

/**
 * Resolves teacher-authored content in the user's selected language when available,
 * never inventing translations when a teacher has not authored one.
 */
export const resolveEntityTranslation = (entity, desiredLanguage) => {
  if (!entity) {
    return {
      title: '',
      description: '',
      content: '',
      activeLanguage: 'en',
      isOriginalFallback: false,
      isFallbackLanguage: false,
      availableLanguages: ['en'],
    };
  }
  const baseLang = normalizeLang(entity.language || 'en');
  const targetLang = normalizeLang(desiredLanguage);
  let map = entity.translations || {};
  if (!Object.keys(map).length && entity.translations_json) {
    try {
      map = typeof entity.translations_json === 'string'
        ? JSON.parse(entity.translations_json)
        : entity.translations_json;
    } catch (_e) {
      map = {};
    }
  }
  const available = Array.from(new Set([baseLang, ...Object.keys(map).map(normalizeLang)]));

  if (targetLang === baseLang && !map[targetLang]) {
    return {
      title: entity.title || '',
      description: entity.description || '',
      content: entity.content || '',
      activeLanguage: baseLang,
      isOriginalFallback: false,
      isFallbackLanguage: false,
      availableLanguages: available,
    };
  }

  if (map[targetLang] && map[targetLang].title) {
    return {
      title: map[targetLang].title,
      description: map[targetLang].description || entity.description || '',
      content: map[targetLang].content || entity.content || '',
      activeLanguage: targetLang,
      isOriginalFallback: false,
      isFallbackLanguage: false,
      availableLanguages: available,
    };
  }

  return {
    title: entity.title || '',
    description: entity.description || '',
    content: entity.content || '',
    activeLanguage: baseLang,
    isOriginalFallback: targetLang !== baseLang,
    isFallbackLanguage: targetLang !== baseLang,
    availableLanguages: available,
  };
};
